#!/usr/bin/env python3
"""Generate missing important symptom chapter files."""

import os

CHAPTERS_DIR = "chapters"
os.makedirs(CHAPTERS_DIR, exist_ok=True)

SECTION_TEMPLATE = r"""\chapter{%(title)s}

\section*{Definition}
%(definition)s

\section*{Pathophysiology}
%(pathophysiology)s

\section*{Etiology}
\begin{itemize}
%(etiology)s\end{itemize}

\section*{Indications for Evaluation}
Seek care if:
\begin{itemize}
%(indications)s\end{itemize}

\section*{Related Symptoms}
\begin{itemize}
%(related)s\end{itemize}

\section*{Self-Care / Home Management}
\begin{itemize}
%(self_care)s\end{itemize}

\section*{Diagnostic Approach}
\begin{itemize}
%(diagnostic)s\end{itemize}

\section*{Treatment / Management Overview}
\begin{itemize}
%(treatment)s\end{itemize}

\clearpage
"""

def make_items(items):
    return '\n'.join(r'  \item ' + item for item in items) + '\n'

def add(name, title, definition, pathophysiology, etiology, indications, related, self_care, diagnostic, treatment):
    data = {
        'title': title,
        'definition': definition,
        'pathophysiology': pathophysiology,
        'etiology': make_items(etiology),
        'indications': make_items(indications),
        'related': make_items(related),
        'self_care': make_items(self_care),
        'diagnostic': make_items(diagnostic),
        'treatment': make_items(treatment),
    }
    filepath = os.path.join(CHAPTERS_DIR, f"symptom_{name}.tex")
    with open(filepath, 'w') as f:
        f.write(SECTION_TEMPLATE % data)
    print(f"  GENERATED: symptom_{name}.tex")

